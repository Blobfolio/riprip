/// # Join Vendor/Model Byte Array.
type VendorModel = [u8; DriveVendorModel::VENDOR_LEN + DriveVendorModel::MODEL_LEN];

#[expect(clippy::cast_possible_wrap, reason = "False positive.")]
/// # Offset Range.
///
/// Ranges outside the ignorable regions in the AccurateRip/CTDB algorithms
/// don't make any practical sense.
const OFFSET_RNG: RangeInclusive<i16> =
	SAMPLES_PER_SECTOR as i16 * -5..=
	SAMPLES_PER_SECTOR as i16 * 5;

// The data generated by build.rs. It is a constant array of known
// (DriveVendorModel, ReadOffset) pairs, and another of known cache sizes.
include!(concat!(env!("OUT_DIR"), "/drives.rs"));



#[derive(Debug, Clone, Copy, Eq, Ord, PartialEq, PartialOrd)]
/// # Drive Vendor/Model.
///
/// Hardware vendor and model identifiers have hard limits of 8 and 16 bytes
/// respectively. By storing them together in a fixed 24-byte array, we can
/// make their values `Copy` while also improving search-by-pair efficiency.
///
/// While probably not strictly necessary, values are stored UPPERCASE to force
/// case insensitivity. They're also required to be ASCII.
///
/// Whitespace cannot be normalized at the point of storage because some pairs
/// differentiate themselves with spacing alone, but the `Display` impl cleans
/// up that nonsense.
pub struct DriveVendorModel {
	/// # Vendor/Model.
	vm: VendorModel,

	/// # Revision.
	rev: [u8; Self::REVISION_LEN],
}

impl fmt::Display for DriveVendorModel {
	fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
		use std::fmt::Write;
		use trimothy::TrimNormalChars;

		/// # No Control.
		const fn no_control(c: char) -> char {
			if c.is_control() { ' ' }
			else { c }
		}

		if let Ok(raw) = std::str::from_utf8(&self.vm) {
			for c in raw.chars().map(no_control).trim_and_normalize() {
				f.write_char(c)?;
			}

			if let Some(revision) = self.revision() {
				write!(f, " [{revision}]")?;
			}
		}

		Ok(())
	}
}

impl DriveVendorModel {
	/// # Max Drive Vendor Length.
	pub const VENDOR_LEN: usize = 8;

	/// # Max Drive Model Length.
	pub const MODEL_LEN: usize = 16;

	/// # Max Drive Revision Length.
	pub const REVISION_LEN: usize = 4;

	/// # New!
	///
	/// Validate and parse separate vendor and model strings into our special
	/// model.
	///
	/// ## Errors
	///
	/// This will return an error if the lengths are out of range, or the
	/// model number is missing.
	pub(crate) fn new(mut vendor: &[u8], mut model: &[u8], mut rev: &[u8])
	-> Result<Self, RipRipError> {
		/// # Trim Value.
		///
		/// This method trims both ASCII whitespace and control characters
		/// from a slice.
		const fn trim(mut src: &[u8]) -> &[u8] {
			while let [ n, rest @ .. ] = src {
				if n.is_ascii_whitespace() || n.is_ascii_control() {
					src = rest;
				}
				else { break; }
			}
			while let [ rest @ .., n ] = src {
				if n.is_ascii_whitespace() || n.is_ascii_control() {
					src = rest;
				}
				else { break; }
			}
			src
		}

		vendor = trim(vendor);
		model = trim(model);
		rev = trim(rev);

		if Self::VENDOR_LEN < vendor.len() || ! vendor.is_ascii() {
			log!(@trace "Invalid drive vendor {vendor:?}.");
			Err(RipRipError::DriveVendor)
		}
		else if ! (1..=Self::MODEL_LEN).contains(&model.len()) || ! model.is_ascii() {
			log!(@trace "Invalid drive model {model:?}.");
			Err(RipRipError::DriveModel)
		}
		else if Self::REVISION_LEN < rev.len() || ! rev.is_ascii() {
			log!(@trace "Invalid drive revision {rev:?}.");
			Err(RipRipError::DriveRevision)
		}
		else {
			// Copy the vendor and model into the joint buffer.
			let mut buf1 = [0_u8; Self::VENDOR_LEN + Self::MODEL_LEN];
			for (b, v) in buf1.iter_mut().zip(vendor) {
				if *v == 0 {
					std::hint::cold_path();
					break;
				}
				*b = v.to_ascii_uppercase();
			}
			for (b, v) in buf1.iter_mut().skip(Self::VENDOR_LEN).zip(model) {
				if *v == 0 {
					std::hint::cold_path();
					break;
				}
				*b = v.to_ascii_uppercase();
			}

			// Copy the revision into its own buffer.
			let mut buf2 = [0_u8; Self::REVISION_LEN];
			for (b, v) in buf2.iter_mut().zip(rev) {
				if *v == 0 {
					std::hint::cold_path();
					break;
				}
				*b = v.to_ascii_uppercase();
			}

			// Done!
			Ok(Self {
				vm: buf1,
				rev: buf2,
			})
		}
	}

	#[must_use]
	/// # Vendor.
	///
	/// Note: This may be empty.
	pub const fn vendor(&self) -> &str {
		if self.vm[0] == 0 { "" }
		else {
			let (mut chunk, _) = self.vm.split_at(Self::VENDOR_LEN);
			while let [ rest @ .., 0 ] = chunk { chunk = rest; }
			if let Ok(out) = std::str::from_utf8(chunk) { out }
			else {
				std::hint::cold_path();
				""
			}
		}
	}

	#[must_use]
	/// # Model.
	///
	/// A model number is always present.
	pub const fn model(&self) -> &str {
		let (_, mut chunk) = self.vm.split_at(Self::VENDOR_LEN);
		while let [ rest @ .., 0 ] = chunk { chunk = rest; }
		if let Ok(out) = std::str::from_utf8(chunk) { out }
		else {
			std::hint::cold_path();
			""
		}
	}

	#[must_use]
	/// # Revision.
	///
	/// Return the drive revision, if any.
	pub const fn revision(&self) -> Option<&str> {
		if self.rev[0] == 0 { None }
		else {
			let mut chunk = self.rev.as_slice();
			while let [ rest @ .., 0 ] = chunk { chunk = rest; }
			if ! chunk.is_empty() && let Ok(out) = std::str::from_utf8(chunk) {
				Some(out)
			}
			else {
				std::hint::cold_path();
				None
			}
		}
	}

	#[must_use]
	/// # Detect Cache Size.
	///
	/// If the vendor/model pair have a known cache size, the value is returned
	/// as a `u16`.
	pub fn detect_cache(&self) -> Option<u16> {
		let Ok(idx) = DRIVE_CACHES.binary_search_by_key(&self.vm, |(k, _)| *k) else {
			log!(@debug "Cache size for drive is unknown.");
			return None;
		};
		log!(
			@debug
			"Assuming {}KiB cache size based on drive.",
			NiceU16::from(DRIVE_CACHES[idx].1),
		);
		Some(DRIVE_CACHES[idx].1)
	}

	#[must_use]
	/// # Detect Offset.
	///
	/// If the vendor/model pair are known, return the drive offset.
	pub fn detect_offset(&self) -> Option<ReadOffset> {
		let Ok(idx) = DRIVE_OFFSETS.binary_search_by_key(&self.vm, |(k, _)| *k) else {
			log!(@debug "Read offset for drive is unknown.");
			return None;
		};
		log!(
			@debug
			"Assuming read offset of {} samples based on drive.",
			DRIVE_OFFSETS[idx].1.samples(),
		);
		Some(DRIVE_OFFSETS[idx].1)
	}
}



#[derive(Debug, Clone, Copy, Default, Eq, Ord, PartialEq, PartialOrd)]
/// # Read Offset.
///
/// This holds a read offset in samples, but can return values in various other
/// useful formats.
///
/// For functional reasons, values are restricted to `-2940..=2940`.
pub struct ReadOffset(i16);

impl TryFrom<i16> for ReadOffset {
	type Error = RipRipError;
	fn try_from(src: i16) -> Result<Self, Self::Error> {
		if OFFSET_RNG.contains(&src) { Ok(Self(src)) }
		else { Err(RipRipError::ReadOffset) }
	}
}

impl TryFrom<&[u8]> for ReadOffset {
	type Error = RipRipError;
	fn try_from(src: &[u8]) -> Result<Self, Self::Error> {
		if src.is_empty() { Ok(Self(0)) }
		else {
			i16::btoi(src)
				.ok_or(RipRipError::ReadOffset)
				.and_then(Self::try_from)
		}
	}
}

impl TryFrom<&str> for ReadOffset {
	type Error = RipRipError;
	fn try_from(src: &str) -> Result<Self, Self::Error> {
		Self::try_from(src.as_bytes())
	}
}

impl ReadOffset {
	#[must_use]
	/// # Is Negative?
	pub const fn is_negative(self) -> bool { self.0 < 0 }

	#[must_use]
	/// # Samples.
	pub const fn samples(self) -> i16 { self.0 }

	#[must_use]
	/// # Samples (Absolute).
	pub const fn samples_abs(self) -> u16 { self.0.abs_diff(0) }
}

impl ReadOffset {
	#[must_use]
	#[expect(clippy::cast_possible_wrap, reason = "False positive.")]
	/// # Sectors.
	///
	/// Return the minimum containing sector amount.
	pub const fn sectors(self) -> i16 {
		// Flip the sector count negative if needed.
		if self.is_negative() { 0 - self.sectors_abs() as i16 }
		else { self.sectors_abs() as i16 }
	}

	#[must_use]
	/// # Sectors (Absolute).
	///
	/// Return the minimum containing sector amount.
	pub const fn sectors_abs(self) -> u16 {
		if self.0 == 0 { return 0; }
		self.samples_abs().div_ceil(SAMPLES_PER_SECTOR)
	}
}



#[cfg(test)]
mod test {
	use super::*;


	#[test]
	fn t_vendormodel() {
		// Test some failures first.
		for (v, m, r) in [
			("", "", ""),
			("Foo", "", ""),
			("Immatoolongvendor", "Bar", ""),
			("Foo", "Immatoolongmodelnumber", ""),
			("Björk", "Model", "Rev"),  // Not ASCII.
			("Vendor", "Björk", "Rev"), // Not ASCII.
			("Vendor", "Model", "1.ö"), // Not ASCII.
			("Vendor", "Model", "Immatoolongrevision"),
		] {
			assert!(DriveVendorModel::new(
				v.as_bytes(),
				m.as_bytes(),
				r.as_bytes(),
			).is_err());
		}

		// Test things that should work.
		let vm = DriveVendorModel::new(
			b"\nPioneer ",
			b"BD-RW   BDR-XD05   ",
			b"1.3",
		)
			.expect("Unable to create DriveVendorModel.");
		assert_eq!(vm.vendor(), "PIONEER");
		assert_eq!(vm.model(), "BD-RW   BDR-XD05");
		assert_eq!(vm.revision(), Some("1.3"));
		assert_eq!(vm.to_string(), "PIONEER BD-RW BDR-XD05 [1.3]");
		assert_eq!(vm.detect_offset(), Some(ReadOffset(667)));
		assert_eq!(vm.detect_cache(), Some(4096));
	}

	#[test]
	fn t_offset() {
		for (raw, samples, samples_abs, sectors, sectors_abs) in [
			("0", 0_i16, 0_u16, 0_i16, 0_u16),
			("123", 123_i16, 123_u16, 1_i16, 1_u16),
			("-123", -123_i16, 123_u16, -1_i16, 1_u16),
			("588", 588_i16, 588_u16, 1_i16, 1_u16),
			("-588", -588_i16, 588_u16, -1_i16, 1_u16),
			("667", 667_i16, 667_u16, 2_i16, 2_u16),
			("-667", -667_i16, 667_u16, -2_i16, 2_u16),
		] {
			let offset = ReadOffset::try_from(raw).expect("ReadOffset failed.");
			assert_eq!(offset.samples(), samples);
			assert_eq!(offset.samples_abs(), samples_abs);
			assert_eq!(offset.sectors(), sectors);
			assert_eq!(offset.sectors_abs(), sectors_abs);
		}

		// Make sure the min and max both work, but no more.
		assert!(ReadOffset::try_from(*OFFSET_RNG.start()).is_ok());
		assert!(ReadOffset::try_from(*OFFSET_RNG.start() - 1).is_err());
		assert!(ReadOffset::try_from(*OFFSET_RNG.end()).is_ok());
		assert!(ReadOffset::try_from(*OFFSET_RNG.end() + 1).is_err());
	}
}
